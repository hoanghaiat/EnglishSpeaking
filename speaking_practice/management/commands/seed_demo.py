r"""
Seed demo data for local manual testing of Phase 1 flows.

Creates (idempotently - safe to run multiple times):
  - demo_admin / demo_teacher / demo_student / demo_parent (password: Demo12345!)
  - teacher profile, student profile, parent profile + their links
  - a sample course "English Speaking Basics" with chapters, lessons,
    exercises, and lesson assignments for the demo student

Usage (PowerShell, project root):
    .\.venv\Scripts\python.exe manage.py seed_demo
    .\.venv\Scripts\python.exe manage.py seed_demo --reset   # delete demo data first
"""
from django.core.management.base import BaseCommand
from django.db import transaction

from speaking_practice.models import (
    User, TeacherProfile, StudentProfile, ParentProfile,
    StudentParent, TeacherStudent, StudentLesson,
    Course, Chapter, Lesson, Exercise,
)

DEMO_PASSWORD = "Demo12345!"
DEMO_COURSE_TITLE = "English Speaking Basics"

DEMO_LESSONS = {
    # chapter_title: [(lesson_title, lesson_description)]
    "Greetings & Introductions": [
        ("Saying Hello", "Learn how to greet people in English."),
        ("Introducing Yourself", "Practice introducing yourself: name, age, school."),
    ],
    "Daily Conversations": [
        ("Asking About the Day", "Small talk: how was your day?"),
        ("Talking About Hobbies", "Describe your hobbies and interests."),
    ],
}

DEMO_EXERCISES = {
    # lesson_title: [(exercise_title, instructions, expected_text)]
    "Saying Hello": [
        ("Greet your teacher", "Say a greeting as if you meet your teacher in the morning.",
         "Good morning, teacher! How are you today?"),
        ("Greet a friend", "Say a casual greeting to a friend.",
         "Hi! Nice to see you. What's up?"),
    ],
    "Introducing Yourself": [
        ("Say your name", "Introduce yourself with your name and age.",
         "Hello, my name is Alex. I am twelve years old."),
        ("Say where you study", "Tell us which school you study at.",
         "I study at Greenfield Secondary School."),
    ],
    "Asking About the Day": [
        ("Ask about the day", "Ask a friend how their day was.",
         "How was your day? What did you do?"),
        ("Answer about your day", "Describe what you did today in two sentences.",
         "My day was good. I played football after school."),
    ],
    "Talking About Hobbies": [
        ("Name your hobby", "Tell us about your favorite hobby.",
         "My favorite hobby is reading books."),
        ("Explain why", "Explain why you like your hobby in two sentences.",
         "I like reading because it is fun and I learn new things."),
    ],
}


class Command(BaseCommand):
    help = "Seed demo users, course content and assignments for Phase 1 manual testing."

    def add_arguments(self, parser):
        parser.add_argument(
            "--reset",
            action="store_true",
            help="Delete previously seeded demo data before creating it again.",
        )

    @transaction.atomic
    def handle(self, *args, **options):
        if options["reset"]:
            self._reset()

        admin = self._get_or_create_user("demo_admin", "admin",
                                         is_staff=True, is_superuser=True)
        teacher_user = self._get_or_create_user("demo_teacher", "teacher")
        student_user = self._get_or_create_user("demo_student", "student")
        parent_user = self._get_or_create_user("demo_parent", "parent")

        teacher = self._get_or_create_profile(TeacherProfile, teacher_user,
                                              bio="Demo teacher account.")
        student = self._get_or_create_profile(StudentProfile, student_user,
                                              grade_level="Grade 7")
        parent = self._get_or_create_profile(ParentProfile, parent_user,
                                             relationship_to_child="Father")

        TeacherStudent.objects.get_or_create(teacher=teacher, student=student)
        StudentParent.objects.get_or_create(
            student=student, parent=parent, relationship_type="Father")

        course, _ = Course.objects.get_or_create(
            title=DEMO_COURSE_TITLE,
            defaults={"description": "Sample course generated by seed_demo."})

        for chapter_order, (chapter_title, lessons) in enumerate(
                DEMO_LESSONS.items(), start=1):
            chapter, _ = Chapter.objects.get_or_create(
                course=course, order=chapter_order,
                defaults={"title": chapter_title})
            for lesson_order, (lesson_title, lesson_desc) in enumerate(
                    lessons, start=1):
                lesson, _ = Lesson.objects.get_or_create(
                    chapter=chapter, order=lesson_order,
                    defaults={"title": lesson_title,
                              "description": lesson_desc,
                              "teacher": teacher})
                for exercise_order, (ex_title, instructions,
                                     expected_text) in enumerate(
                        DEMO_EXERCISES[lesson_title], start=1):
                    Exercise.objects.get_or_create(
                        lesson=lesson, order=exercise_order,
                        defaults={"title": ex_title,
                                  "instructions": instructions,
                                  "expected_text": expected_text})
                StudentLesson.objects.get_or_create(
                    student=student, lesson=lesson)

        self.stdout.write(self.style.SUCCESS(
            "Demo data ready. Log in with:\n"
            f"  admin   -> demo_admin   (superuser)\n"
            f"  teacher -> demo_teacher\n"
            f"  student -> demo_student\n"
            f"  parent  -> demo_parent\n"
            f"Password for all demo accounts: {DEMO_PASSWORD}"
        ))

    def _get_or_create_user(self, username, role, **extra):
        user, created = User.objects.get_or_create(
            username=username,
            defaults={"role": role, "email": f"{username}@example.com",
                      **extra})
        if created:
            user.set_password(DEMO_PASSWORD)
            user.save(update_fields=["password"])
            self.stdout.write(f"Created user {username} ({role})")
        return user

    def _get_or_create_profile(self, model, user, **defaults):
        profile, created = model.objects.get_or_create(user=user,
                                                       defaults=defaults)
        if created:
            self.stdout.write(f"Created {model.__name__} for {user.username}")
        return profile

    def _reset(self):
        deleted_users, _ = User.objects.filter(
            username__in=["demo_admin", "demo_teacher",
                          "demo_student", "demo_parent"]).delete()
        deleted_courses, _ = Course.objects.filter(
            title=DEMO_COURSE_TITLE).delete()
        self.stdout.write(
            f"Reset demo data: {deleted_users} users, "
            f"{deleted_courses} courses removed.")
